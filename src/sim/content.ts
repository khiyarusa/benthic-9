export const ROOM_IDS = ROOMS.map((room) => room.id);

export const ROOM_VOLUME: Record<RoomId, number> = ROOMS.reduce(
  (acc, room) => {
    acc[room.id] = room.volumeM3;
    return acc;
  },
  {} as Record<RoomId, number>,
);

export const ROOM_LABEL: Record<RoomId, string> = ROOMS.reduce(
  (acc, room) => {
    acc[room.id] = room.label;
    return acc;
  },
  {} as Record<RoomId, string>,
);

export function roomDef(id: RoomId): RoomDefinition {
  const found = ROOMS.find((room) => room.id === id);
  if (!found) throw new Error(`Unknown room: ${id}`);
  return found;
}

