export function HelpPanel() {
  const progress = loadTutorialProgress();
  const status = progress.done ? 'تکمیل‌شده' : progress.paused ? 'متوقف‌شده' : 'در جریان';

  return (
    <div>
      <div className="help-intro">
        <div>
          <strong>راهنمای فرمانده</strong>
          <p>
            این بخش همیشه در دسترس است. اگر جایی گم شدی، همین‌جا پاسخ بیشتر سؤال‌ها را پیدا
            می‌کنی.
          </p>
        </div>
        <div className="help-tutorial">
          <span className="chip">آموزش: {status}</span>
          <button type="button" className="btn btn--sm" onClick={() => resumeTutorial()}>
            {progress.done ? 'شروع دوبارهٔ آموزش' : 'ادامهٔ آموزش'}
          </button>
          <button type="button" className="btn btn--sm btn--ghost" onClick={() => restartTutorial()}>
            از ابتدا
          </button>
        </div>
      </div>

      <Section title="موضوع‌ها">
        <div className="help-topics">
          {TOPICS.map((topic) => (
            <details key={topic.id} className="help-topic">
              <summary>{topic.title}</summary>
              <ul>
                {topic.body.map((line, index) => (
                  <li key={index}>{line}</li>
                ))}
              </ul>
            </details>
          ))}
        </div>
      </Section>

      <p className="hint">
        نکته: هر پنل، اطلاعات خودش را از وضعیت واقعی شبیه‌سازی می‌گیرد؛ هیچ عدد تزئینی در بازی
        نیست.
      </p>
    </div>
  );
}
